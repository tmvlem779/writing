export function evaluateGrammarConceptCheck(lessonId: string, optionId: string) {
  const lesson = grammarElementLessons.find((item) => item.id === lessonId);
  if (!lesson) return null;
  const check = [lesson.check, ...(lesson.extraChecks ?? [])].find((item) => item.options.some((option) => option.id === optionId));
  if (!check) return null;
  return {
    correct: check.answer === optionId,
    feedback: check.feedback,
    reflection: check.reflection
  };
}
